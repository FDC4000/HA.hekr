from __future__ import annotations

from unittest.mock import patch

import pytest
from homeassistant.const import CONF_PASSWORD, CONF_USERNAME
from homeassistant.core import HomeAssistant
from homeassistant.helpers import entity_registry as er
from pytest_homeassistant_custom_component.common import MockConfigEntry

from custom_components.hekr_wisen.const import DATA_DEVICES, DEVICE_URL, DOMAIN, LOGIN_URL

_DEV_TID = "ESP_2M_TESTDEVICE"


class _FakeWS:
    """Stand-in for HekrWebsocket: no real connection, records sent frames."""

    instances: list["_FakeWS"] = []

    def __init__(self, session, token_provider, status_cb, avail_cb):
        self.status_cb = status_cb
        self.avail_cb = avail_cb
        self.sent: list[tuple[str, str, str]] = []
        _FakeWS.instances.append(self)

    @property
    def connected(self) -> bool:
        return True

    def start(self) -> None:
        self.avail_cb(True)

    async def stop(self) -> None:
        self.avail_cb(False)

    async def async_send_command(self, dev_tid, ctrl_key, raw) -> None:
        self.sent.append((dev_tid, ctrl_key, raw))


@pytest.fixture
def mock_entry(hass: HomeAssistant, device_response) -> MockConfigEntry:
    entry = MockConfigEntry(
        domain=DOMAIN,
        unique_id="user@example.com",
        data={
            CONF_USERNAME: "user@example.com",
            CONF_PASSWORD: "secret",
            DATA_DEVICES: device_response,
        },
        options={},
    )
    entry.add_to_hass(hass)
