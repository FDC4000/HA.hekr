async def _setup(hass, aioclient_mock, entry, login_response, device_response):
    aioclient_mock.post(LOGIN_URL, json=login_response)
    aioclient_mock.get(DEVICE_URL, json=device_response)
    _FakeWS.instances.clear()
    with patch(
        "custom_components.hekr_wisen.coordinator.HekrWebsocket", _FakeWS
    ):
        assert await hass.config_entries.async_setup(entry.entry_id)
        await hass.async_block_till_done()


async def test_entities_created(
    hass, aioclient_mock, mock_entry, login_response, device_response
):
    await _setup(hass, aioclient_mock, mock_entry, login_response, device_response)
    entities = er.async_get(hass).entities
    domains = {e.domain for e in entities.values()}
    assert {"fan", "switch", "light", "binary_sensor", "button", "number", "sensor"} <= domains


async def test_status_push_updates_state(
    hass, aioclient_mock, mock_entry, login_response, device_response
):
    await _setup(hass, aioclient_mock, mock_entry, login_response, device_response)
    coordinator = mock_entry.runtime_data
    coordinator._on_status(
        _DEV_TID,
        {"sw": 1, "light_Sw": 0, "speed": 2, "fitter": 1, "Statue": 2},
    )
    await hass.async_block_till_done()

    reg = er.async_get(hass)
    power_id = reg.async_get_entity_id("switch", DOMAIN, f"{_DEV_TID}_power")
    filter_id = reg.async_get_entity_id("binary_sensor", DOMAIN, f"{_DEV_TID}_filter")
    assert hass.states.get(power_id).state == "on"
    assert hass.states.get(filter_id).state == "on"


async def test_command_builds_correct_frame(
    hass, aioclient_mock, mock_entry, login_response, device_response
):
    await _setup(hass, aioclient_mock, mock_entry, login_response, device_response)
    reg = er.async_get(hass)
    power_id = reg.async_get_entity_id("switch", DOMAIN, f"{_DEV_TID}_power")

    await hass.services.async_call(
        "switch", "turn_on", {"entity_id": power_id}, blocking=True
    )

    # Default checksum mode is "calc": frame_set_switch(True) == 48070200020154
    assert _FakeWS.instances[-1].sent[-1][2] == "48070200020154"
