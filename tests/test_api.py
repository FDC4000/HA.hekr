from __future__ import annotations

import aiohttp
import pytest
from homeassistant.core import HomeAssistant
from homeassistant.helpers.aiohttp_client import async_get_clientsession

from custom_components.hekr_hood.api import (
    HekrAuthError,
    HekrCloudApi,
    HekrConnectionError,
)
from custom_components.hekr_hood.const import DEVICE_URL, LOGIN_URL


async def test_login_success(hass: HomeAssistant, aioclient_mock, login_response):
    aioclient_mock.post(LOGIN_URL, json=login_response)
    api = HekrCloudApi(async_get_clientsession(hass))
    result = await api.async_login("user@example.com", "secret")
    assert result["access_token"] == "test-token"


async def test_login_invalid_auth(hass: HomeAssistant, aioclient_mock):
    aioclient_mock.post(LOGIN_URL, status=401, json={"code": 3400010})
    api = HekrCloudApi(async_get_clientsession(hass))
    with pytest.raises(HekrAuthError):
        await api.async_login("user@example.com", "wrong")


async def test_login_connection_error(hass: HomeAssistant, aioclient_mock):
    aioclient_mock.post(LOGIN_URL, exc=aiohttp.ClientConnectionError("boom"))
    api = HekrCloudApi(async_get_clientsession(hass))
    with pytest.raises(HekrConnectionError):
        await api.async_login("user@example.com", "secret")


async def test_get_devices(hass: HomeAssistant, aioclient_mock, device_response):
    aioclient_mock.get(DEVICE_URL, json=device_response)
    api = HekrCloudApi(async_get_clientsession(hass))
    devices = await api.async_get_devices("test-token")
    assert len(devices) == 1
    assert devices[0]["model"] == "M002"
