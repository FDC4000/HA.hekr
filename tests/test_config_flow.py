from __future__ import annotations

from unittest.mock import patch

from homeassistant import config_entries, data_entry_flow
from homeassistant.core import HomeAssistant

from custom_components.hekr_wisen.const import DEVICE_URL, DOMAIN, LOGIN_URL


async def test_user_flow_success(
    hass: HomeAssistant, aioclient_mock, login_response, device_response
) -> None:
    aioclient_mock.post(LOGIN_URL, json=login_response)
    aioclient_mock.get(DEVICE_URL, json=device_response)

    result = await hass.config_entries.flow.async_init(
        DOMAIN, context={"source": config_entries.SOURCE_USER}
    )
    assert result["type"] is data_entry_flow.FlowResultType.FORM

    with patch(
        "custom_components.hekr_wisen.async_setup_entry", return_value=True
    ):
        result = await hass.config_entries.flow.async_configure(
            result["flow_id"],
            {"username": "user@example.com", "password": "secret"},
        )

    assert result["type"] is data_entry_flow.FlowResultType.CREATE_ENTRY
    assert result["data"]["username"] == "user@example.com"
    assert result["data"]["devices"][0]["model"] == "M002"


async def test_user_flow_invalid_auth(hass: HomeAssistant, aioclient_mock) -> None:
    aioclient_mock.post(LOGIN_URL, status=401, json={"code": 3400010})

    result = await hass.config_entries.flow.async_init(
        DOMAIN, context={"source": config_entries.SOURCE_USER}
    )
    result = await hass.config_entries.flow.async_configure(
        result["flow_id"],
        {"username": "user@example.com", "password": "wrong"},
    )

    assert result["type"] is data_entry_flow.FlowResultType.FORM
    assert result["errors"] == {"base": "invalid_auth"}


async def test_single_instance(
    hass: HomeAssistant, aioclient_mock, login_response, device_response
) -> None:
    aioclient_mock.post(LOGIN_URL, json=login_response)
    aioclient_mock.get(DEVICE_URL, json=device_response)

    with patch("custom_components.hekr_wisen.async_setup_entry", return_value=True):
        first = await hass.config_entries.flow.async_init(
            DOMAIN, context={"source": config_entries.SOURCE_USER}
        )
        await hass.config_entries.flow.async_configure(
            first["flow_id"],
            {"username": "user@example.com", "password": "secret"},
        )
        second = await hass.config_entries.flow.async_init(
            DOMAIN, context={"source": config_entries.SOURCE_USER}
        )
        result = await hass.config_entries.flow.async_configure(
            second["flow_id"],
            {"username": "user@example.com", "password": "secret"},
        )

    assert result["type"] is data_entry_flow.FlowResultType.ABORT
    assert result["reason"] == "already_configured"
