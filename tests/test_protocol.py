"""Unit tests for the Hekr transparent frame encoder.

Generated by aurora@aurora-smart-home (ha-integration-dev skill)
https://github.com/tonylofgren/aurora-smart-home

These tests are self-contained: they load ``const`` and ``protocol`` directly
from file under a synthetic ``hekr_wisen`` package so they run without Home
Assistant installed (the package ``__init__`` imports HA and is bypassed here).
"""

from __future__ import annotations

import importlib.util
import pathlib
import sys
import types

_BASE = pathlib.Path(__file__).resolve().parents[1] / "custom_components" / "hekr_wisen"


def _load(mod_name: str, filename: str):
    spec = importlib.util.spec_from_file_location(mod_name, _BASE / filename)
    assert spec and spec.loader
    module = importlib.util.module_from_spec(spec)
    sys.modules[mod_name] = module
    spec.loader.exec_module(module)
    return module


# Register a synthetic package so protocol's ``from .const import`` resolves
# without executing the real __init__.py (which imports Home Assistant).
if "hekr_wisen" not in sys.modules:
    _pkg = types.ModuleType("hekr_wisen")
    _pkg.__path__ = [str(_BASE)]
    sys.modules["hekr_wisen"] = _pkg

const = _load("hekr_wisen.const", "const.py")
protocol = _load("hekr_wisen.protocol", "protocol.py")


def _checksum(hex_frame: str) -> int:
    """Return the sum of all but the last byte, masked to a byte."""
    data = bytes.fromhex(hex_frame)
    return sum(data[:-1]) & 0xFF


def test_switch_on_calc_checksum():
    frame = protocol.frame_set_switch(True, checksum_mode=const.CHECKSUM_CALC)
    # 48 07 02 00 02 01 <cksum>; sum = 0x54
    assert frame == "48070200020154"
    assert bytes.fromhex(frame)[-1] == 0x54


def test_switch_on_zero_checksum_matches_original():
    # The original main.js emits "48070200" + "02" + "01" + "00".
    frame = protocol.frame_set_switch(True, checksum_mode=const.CHECKSUM_ZERO)
    assert frame == "48070200020100"


def test_switch_off():
    frame = protocol.frame_set_switch(False, checksum_mode=const.CHECKSUM_ZERO)
    assert frame == "48070200020000"


def test_speed_length_byte():
    frame = protocol.frame_set_speed(3, checksum_mode=const.CHECKSUM_CALC)
    raw = bytes.fromhex(frame)
    assert raw[0] == 0x48
    assert raw[1] == 0x07  # base 6 + 1 data byte
    assert raw[4] == const.CMD_SET_SPEED
    assert raw[5] == 3
    assert raw[-1] == _checksum(frame)


def test_rgb_m002_includes_switch_byte():
    # M002: payload [RGB_Sw, R, G, B] -> length 0x0a
    frame = protocol.frame_set_rgbw(
        0x65, 0xFF, 0x00, model="M002", checksum_mode=const.CHECKSUM_CALC
    )
    raw = bytes.fromhex(frame)
    assert raw[1] == 0x0A
    assert raw[4] == const.CMD_SET_RGBW
    assert list(raw[5:9]) == [0x01, 0x65, 0xFF, 0x00]
    assert raw[-1] == _checksum(frame)


def test_rgb_m001_omits_switch_byte_matches_original():
    # M001 / original main.js: "48090200" + "07" + "65ff00" + "00"
    frame = protocol.frame_set_rgbw(
        0x65, 0xFF, 0x00, model="M001", checksum_mode=const.CHECKSUM_ZERO
    )
    assert frame == "480902000765ff0000"


def test_rgb_off_sends_switch_zero():
    frame = protocol.frame_set_rgbw(0, 0, 0, rgb_on=False, model="M002")
    raw = bytes.fromhex(frame)
    assert raw[5] == 0x00  # RGB_Sw = 0


def test_timer_range():
    import pytest

    with pytest.raises(ValueError):
        protocol.frame_set_timer(61)
    frame = protocol.frame_set_timer(30, checksum_mode=const.CHECKSUM_CALC)
    assert bytes.fromhex(frame)[5] == 30


def test_timing_frame():
    frame = protocol.frame_timing(13, 5, 9, checksum_mode=const.CHECKSUM_ZERO)
    # bytes: 48 09 02 00 08 0d 05 09 00
    assert frame == "48090200080d050900"
    raw = bytes.fromhex(frame)
    assert raw[0] == const.FRAME_HEADER
    assert raw[1] == 0x09  # base 6 + 3 data bytes
    assert raw[4] == const.CMD_TIMING
    assert list(raw[5:8]) == [13, 5, 9]
    assert raw[-1] == 0x00


def test_byte_value_out_of_range():
    import pytest

    with pytest.raises(ValueError):
        protocol.build_frame(2, [256])


def test_query_frame_has_no_payload():
    # Query (cmdId 0) carries no data bytes: 48 06 02 00 00 <cksum>.
    frame = protocol.frame_query(checksum_mode=const.CHECKSUM_CALC)
    raw = bytes.fromhex(frame)
    assert raw[0] == const.FRAME_HEADER
    assert raw[1] == 0x06  # base length, zero data bytes
    assert raw[2] == const.FRAME_TYPE_CONTROL
    assert raw[4] == const.CMD_QUERY
    assert len(raw) == 6
    # sum(48 06 02 00 00) & 0xff == 0x50
    assert frame == "480602000050"
    assert raw[-1] == _checksum(frame)


def test_query_frame_zero_checksum():
    frame = protocol.frame_query(checksum_mode=const.CHECKSUM_ZERO)
    assert frame == "480602000000"
