from __future__ import annotations

from typing import Any

from homeassistant.components.light import ColorMode, LightEntity
from homeassistant.core import HomeAssistant
from homeassistant.helpers.entity_platform import AddConfigEntryEntitiesCallback

from . import protocol
from .const import (
    FIELD_B,
    FIELD_G,
    FIELD_LIGHT,
    FIELD_R,
    FIELD_RGB_SW,
)
from .coordinator import HekrConfigEntry
from .entity import HekrEntity


async def async_setup_entry(
    hass: HomeAssistant,
    entry: HekrConfigEntry,
    async_add_entities: AddConfigEntryEntitiesCallback,
) -> None:
    """Set up the light entities."""
    coordinator = entry.runtime_data
    entities: list[HekrEntity] = []
    for tid in coordinator.devices:
        entities.append(HekrSpotlight(coordinator, tid))
        entities.append(HekrRgbLight(coordinator, tid))
    async_add_entities(entities)


class HekrSpotlight(HekrEntity, LightEntity):
    """White spotlight (light_Sw), on/off only."""

    _attr_translation_key = "spotlight"
    _attr_color_mode = ColorMode.ONOFF
    _attr_supported_color_modes = {ColorMode.ONOFF}

    def __init__(self, coordinator, dev_tid: str) -> None:
        super().__init__(coordinator, dev_tid)
        self._attr_unique_id = f"{dev_tid}_spotlight"

    @property
    def is_on(self) -> bool:
        return bool(self._status.get(FIELD_LIGHT))

    async def async_turn_on(self, **kwargs: Any) -> None:
        await self._async_send(
            protocol.frame_set_light(True, checksum_mode=self.coordinator.checksum_mode)
        )

    async def async_turn_off(self, **kwargs: Any) -> None:
        await self._async_send(
            protocol.frame_set_light(False, checksum_mode=self.coordinator.checksum_mode)
        )


class HekrRgbLight(HekrEntity, LightEntity):
    """RGB decorative light (RGB_Sw + R/G/B)."""

    _attr_translation_key = "rgb"
    _attr_color_mode = ColorMode.RGB
    _attr_supported_color_modes = {ColorMode.RGB}

    def __init__(self, coordinator, dev_tid: str) -> None:
        super().__init__(coordinator, dev_tid)
        self._attr_unique_id = f"{dev_tid}_rgb"

    @property
    def is_on(self) -> bool:
        return bool(self._status.get(FIELD_RGB_SW))

    @property
    def rgb_color(self) -> tuple[int, int, int]:
        status = self._status
        return (
            int(status.get(FIELD_R, 0) or 0),
            int(status.get(FIELD_G, 0) or 0),
            int(status.get(FIELD_B, 0) or 0),
        )

    @property
    def brightness(self) -> int | None:
        # Device exposes no brightness channel; colour carries the intensity.
        return None

    async def async_turn_on(self, **kwargs: Any) -> None:
        from homeassistant.components.light import ATTR_RGB_COLOR

        red, green, blue = kwargs.get(ATTR_RGB_COLOR, self.rgb_color)
        if (red, green, blue) == (0, 0, 0):
            # Avoid turning on to black; default to white.
            red = green = blue = 255
        await self._async_send(
            protocol.frame_set_rgbw(
                red,
                green,
                blue,
                rgb_on=True,
                model=self.coordinator.model_for(self._dev_tid),
                checksum_mode=self.coordinator.checksum_mode,
            )
        )

    async def async_turn_off(self, **kwargs: Any) -> None:
        red, green, blue = self.rgb_color
        await self._async_send(
            protocol.frame_set_rgbw(
                red,
                green,
                blue,
                rgb_on=False,
                model=self.coordinator.model_for(self._dev_tid),
                checksum_mode=self.coordinator.checksum_mode,
            )
        )
