from __future__ import annotations

from typing import Any

from homeassistant.components.switch import SwitchEntity
from homeassistant.core import HomeAssistant
from homeassistant.helpers.entity_platform import AddConfigEntryEntitiesCallback

from . import protocol
from .const import FIELD_SW
from .coordinator import HekrConfigEntry
from .entity import HekrEntity


async def async_setup_entry(
    hass: HomeAssistant,
    entry: HekrConfigEntry,
    async_add_entities: AddConfigEntryEntitiesCallback,
) -> None:
    """Set up the main power switch."""
    coordinator = entry.runtime_data
    async_add_entities(HekrPowerSwitch(coordinator, tid) for tid in coordinator.devices)


class HekrPowerSwitch(HekrEntity, SwitchEntity):
    """The device master power (sw)."""

    _attr_translation_key = "power"

    def __init__(self, coordinator, dev_tid: str) -> None:
        super().__init__(coordinator, dev_tid)
        self._attr_unique_id = f"{dev_tid}_power"

    @property
    def is_on(self) -> bool:
        return bool(self._status.get(FIELD_SW))

    async def async_turn_on(self, **kwargs: Any) -> None:
        await self._async_switch(True)

    async def async_turn_off(self, **kwargs: Any) -> None:
        await self._async_switch(False)

    async def _async_switch(self, on: bool) -> None:
        raw = protocol.frame_set_switch(on, checksum_mode=self.coordinator.checksum_mode)
        await self._async_send(raw, optimistic={FIELD_SW: 1 if on else 0})
