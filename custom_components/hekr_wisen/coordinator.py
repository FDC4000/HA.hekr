"""DataUpdateCoordinator for the Hekr / Wisen integration.

Generated by aurora@aurora-smart-home (ha-integration-dev skill)
https://github.com/tonylofgren/aurora-smart-home

Push-based: status arrives via the cloud WebSocket and is pushed into the
coordinator with ``async_set_updated_data``. There is no polling interval.
"""

from __future__ import annotations

import logging
from typing import Any

from homeassistant.config_entries import ConfigEntry
from homeassistant.const import CONF_PASSWORD, CONF_USERNAME
from homeassistant.core import CALLBACK_TYPE, HomeAssistant, callback
from homeassistant.exceptions import ConfigEntryAuthFailed
from homeassistant.helpers.aiohttp_client import async_get_clientsession
from homeassistant.helpers.event import async_call_later
from homeassistant.helpers.update_coordinator import DataUpdateCoordinator, UpdateFailed

from .api import HekrAuthError, HekrCloudApi, HekrConnectionError
from .const import (
    CHECKSUM_CALC,
    CONF_CHECKSUM_MODE,
    CONF_USE_UDP,
    DATA_CTRLKEY,
    DATA_DEVICES,
    DATA_DEVTID,
    DATA_LANIP,
    DATA_MODEL,
    DATA_NAME,
    DOMAIN,
)
from .local import async_send_local
from .websocket import HekrWebsocket
from . import protocol

_LOGGER = logging.getLogger(__name__)

type HekrConfigEntry = ConfigEntry["HekrCoordinator"]

# Re-login a little before the token actually expires.
_TOKEN_REFRESH_FACTOR = 0.9
_DEFAULT_EXPIRES_IN = 86400

# Delay the reconcile status query so the device has applied the command
# before it reports, avoiding a race where the reply carries the pre-command
# value and briefly overwrites the optimistic state.
_REFRESH_DELAY = 1.5  # seconds


class HekrCoordinator(DataUpdateCoordinator[dict[str, dict[str, Any]]]):
    """Owns the cloud session, the WebSocket and per-device status."""

    config_entry: HekrConfigEntry

    def __init__(self, hass: HomeAssistant, entry: HekrConfigEntry) -> None:
        super().__init__(
            hass,
            _LOGGER,
            name=DOMAIN,
            config_entry=entry,
            update_interval=None,  # push only
        )
        self.api = HekrCloudApi(async_get_clientsession(hass))
        self.devices: dict[str, dict[str, Any]] = {
            dev[DATA_DEVTID]: dev for dev in entry.data.get(DATA_DEVICES, [])
        }
        self._token: str | None = None
        self._available = False
        self._cancel_relogin = None
        self._refresh_cancels: dict[str, CALLBACK_TYPE] = {}
        self.ws = HekrWebsocket(
            async_get_clientsession(hass),
            self._async_get_token,
            self._on_status,
            self._on_availability,
        )

    # --- lifecycle --------------------------------------------------------

    async def async_setup(self) -> None:
        """Log in, refresh the device list and start the WebSocket."""
        await self._async_login()
        await self._async_refresh_devices()
        # Seed empty status so entities are created before the first push.
        self.async_set_updated_data({tid: {} for tid in self.devices})
        self.ws.start()

    async def async_shutdown(self) -> None:
        """Tear down the WebSocket and scheduled re-login."""
        if self._cancel_relogin is not None:
            self._cancel_relogin()
            self._cancel_relogin = None
        for cancel in self._refresh_cancels.values():
            cancel()
        self._refresh_cancels.clear()
        await self.ws.stop()
        await super().async_shutdown()

    # --- auth -------------------------------------------------------------

    async def _async_login(self) -> None:
        try:
            info = await self.api.async_login(
                self.config_entry.data[CONF_USERNAME],
                self.config_entry.data[CONF_PASSWORD],
            )
        except HekrAuthError as err:
            raise ConfigEntryAuthFailed(str(err)) from err
        except HekrConnectionError as err:
            raise UpdateFailed(str(err)) from err
        self._token = info["access_token"]
        expires_in = info.get("expires_in") or _DEFAULT_EXPIRES_IN
        self._schedule_relogin(expires_in * _TOKEN_REFRESH_FACTOR)

    def _schedule_relogin(self, delay: float) -> None:
        if self._cancel_relogin is not None:
            self._cancel_relogin()

        async def _relogin(_now) -> None:
            self._cancel_relogin = None
            try:
                await self._async_login()
            except (ConfigEntryAuthFailed, UpdateFailed) as err:
                _LOGGER.warning("Token refresh failed: %s", err)
                self._schedule_relogin(300)
                return
            # Reconnect the socket so appLogin uses the fresh token.
            await self.ws.stop()
            self.ws.start()

        self._cancel_relogin = async_call_later(self.hass, delay, _relogin)

    async def _async_get_token(self) -> str:
        if self._token is None:
            await self._async_login()
        assert self._token is not None
        return self._token

    async def _async_refresh_devices(self) -> None:
        """Refresh LAN IP / online state from the cloud (best effort)."""
        try:
            devices = await self.api.async_get_devices(await self._async_get_token())
        except (HekrAuthError, HekrConnectionError) as err:
            _LOGGER.debug("Device refresh skipped: %s", err)
            return
        for dev in devices:
            tid = dev.get(DATA_DEVTID)
            if tid and tid in self.devices:
                self.devices[tid].update(dev)

    # --- status push ------------------------------------------------------

    @callback
    def _apply_status(self, dev_tid: str, status: dict[str, Any]) -> None:
        """Merge a status fragment into a device's data and notify listeners."""
        merged = dict(self.data or {})
        current = dict(merged.get(dev_tid, {}))
        current.update(status)
        merged[dev_tid] = current
        self.async_set_updated_data(merged)

    @callback
    def _on_status(self, dev_tid: str, status: dict[str, Any]) -> None:
        # Device-report entry point only (optimistic updates go through
        # async_set_optimistic). Logs the raw report so a real devSend can be
        # told apart from an optimistic write, and its exact field keys seen.
        _LOGGER.debug("devSend report for %s: %s", dev_tid, status)
        self._apply_status(dev_tid, status)

    @callback
    def async_set_optimistic(self, dev_tid: str, patch: dict[str, Any]) -> None:
        """Apply an assumed state immediately after sending a command.

        This is an optimistic update: the UI reflects the expected values at
        once (0 s wait), and the device's next status report overwrites them
        with reality (reconciliation). Identical merge semantics as an incoming
        report, so a later report for the same fields simply replaces these.
        """
        if not patch:
            return
        self._apply_status(dev_tid, patch)

    @callback
    def async_request_device_refresh(self, dev_tid: str) -> None:
        """Schedule a status query shortly after a command (reconciliation).

        Sends the transparent query command (cmdId 0) after ``_REFRESH_DELAY``
        so the real state is pulled in without waiting for the device's next
        unsolicited report, while giving the device time to apply the command
        first.

        The pending query is tracked per device and debounced: a second command
        within the delay cancels the still-pending query and reschedules, so
        only one query fires ``_REFRESH_DELAY`` after the last command. All
        pending timers are cancelled on shutdown, so a query never fires into a
        torn-down entry. If the device ignores the query the optimistic state
        still reconciles on a later report; failures are swallowed so a refresh
        never breaks the command that triggered it.
        """
        existing = self._refresh_cancels.pop(dev_tid, None)
        if existing is not None:
            existing()

        async def _query(_now) -> None:
            self._refresh_cancels.pop(dev_tid, None)
            try:
                await self.async_send_raw(
                    dev_tid, protocol.frame_query(checksum_mode=self.checksum_mode)
                )
            except Exception as err:  # noqa: BLE001 - refresh is strictly best effort
                _LOGGER.debug("Status refresh request failed for %s: %s", dev_tid, err)

        self._refresh_cancels[dev_tid] = async_call_later(
            self.hass, _REFRESH_DELAY, _query
        )

    @callback
    def _on_availability(self, available: bool) -> None:
        if available == self._available:
            return
        self._available = available
        self.async_update_listeners()

    @property
    def available(self) -> bool:
        """Return whether the cloud WebSocket is connected."""
        return self._available

    # --- commands ---------------------------------------------------------

    @property
    def _checksum_mode(self) -> str:
        return self.config_entry.options.get(CONF_CHECKSUM_MODE, CHECKSUM_CALC)

    @property
    def _use_udp(self) -> bool:
        return self.config_entry.options.get(CONF_USE_UDP, False)

    def model_for(self, dev_tid: str) -> str | None:
        """Return the model string for a device, if known."""
        return self.devices.get(dev_tid, {}).get(DATA_MODEL)

    def device_name(self, dev_tid: str) -> str:
        """Return the friendly device name."""
        return self.devices.get(dev_tid, {}).get(DATA_NAME, dev_tid)

    async def async_send_raw(self, dev_tid: str, raw: str) -> None:
        """Send a prepared raw frame to a device (UDP if enabled, else WS)."""
        device = self.devices.get(dev_tid, {})
        ctrl_key = device.get(DATA_CTRLKEY)
        if not ctrl_key:
            raise UpdateFailed(f"missing ctrlKey for {dev_tid}")
        lan_ip = device.get(DATA_LANIP)
        if self._use_udp and lan_ip:
            await async_send_local(lan_ip, dev_tid, ctrl_key, raw)
            return
        await self.ws.async_send_command(dev_tid, ctrl_key, raw)

    @property
    def checksum_mode(self) -> str:
        """Expose the configured checksum mode to entity frame builders."""
        return self._checksum_mode
