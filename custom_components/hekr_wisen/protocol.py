"""Hekr transparent (JSON_TRANSPARENT) frame encoding/decoding.

Generated by aurora@aurora-smart-home (ha-integration-dev skill)
https://github.com/tonylofgren/aurora-smart-home

Ported from the ioBroker.hekr adapter by TA2k
(https://github.com/TA2k/ioBroker.hekr), MIT License, Copyright (c) 2021 TA2k.

Frame layout (TRANSPARENT / 0x48 protocol), per the official Hekr web SDK::

    [0x48, length, frameType, msgId, cmdId, *data_bytes, checksum]

    length   = FRAME_BASE_LENGTH + len(data_bytes)   (total byte count)
    checksum = sum(all preceding bytes) & 0xFF

The original ``main.js`` hard-codes the trailing checksum byte to ``0x00``
instead of computing it. Cloud delivery tolerates this (the cloud re-signs the
frame), but a device addressed directly over the LAN very likely rejects a bad
checksum. This module therefore supports both modes via ``checksum_mode``.
"""

from __future__ import annotations

from collections.abc import Sequence

from .const import (
    CHECKSUM_CALC,
    CMD_RESET_CLEANING,
    CMD_SET_LIGHT,
    CMD_SET_RGBW,
    CMD_SET_SPEED,
    CMD_SET_SW,
    CMD_SET_TIMER,
    CMD_TIMING,
    FRAME_BASE_LENGTH,
    FRAME_HEADER,
    FRAME_TYPE_CONTROL,
    RGB_MODELS_WITHOUT_SWITCH,
)


def build_frame(
    cmd_id: int,
    data_bytes: Sequence[int],
    *,
    frame_type: int = FRAME_TYPE_CONTROL,
    msg_id: int = 0,
    checksum_mode: str = CHECKSUM_CALC,
) -> str:
    """Build a transparent protocol frame and return it as a lowercase hex string.

    ``data_bytes`` are the command payload bytes (already validated by the
    caller). Each value must fit in a single byte (0-255).
    """
    for value in data_bytes:
        if not 0 <= value <= 0xFF:
            raise ValueError(f"byte value out of range: {value}")

    length = FRAME_BASE_LENGTH + len(data_bytes)
    frame = [
        FRAME_HEADER,
        length & 0xFF,
        frame_type & 0xFF,
        msg_id & 0xFF,
        cmd_id & 0xFF,
        *data_bytes,
    ]
    checksum = (sum(frame) & 0xFF) if checksum_mode == CHECKSUM_CALC else 0x00
    frame.append(checksum)
    return "".join(f"{byte:02x}" for byte in frame)


# --- High level command builders -----------------------------------------


def frame_set_switch(on: bool, **kwargs: str) -> str:
    """Main power (sw)."""
    return build_frame(CMD_SET_SW, [1 if on else 0], **kwargs)


def frame_set_light(on: bool, **kwargs: str) -> str:
    """White spotlight (light_Sw)."""
    return build_frame(CMD_SET_LIGHT, [1 if on else 0], **kwargs)


def frame_set_speed(speed: int, **kwargs: str) -> str:
    """Fan speed (0 = off, 1-4)."""
    if not 0 <= speed <= 4:
        raise ValueError(f"speed out of range (0-4): {speed}")
    return build_frame(CMD_SET_SPEED, [speed], **kwargs)


def frame_set_timer(minutes: int, **kwargs: str) -> str:
    """Auto-off timer in minutes (0 = off, 1-60)."""
    if not 0 <= minutes <= 60:
        raise ValueError(f"timer out of range (0-60): {minutes}")
    return build_frame(CMD_SET_TIMER, [minutes], **kwargs)


def frame_reset_cleaning(value: int = 1, **kwargs: str) -> str:
    """Reset the filter-change reminder (rest_Cleaning)."""
    return build_frame(CMD_RESET_CLEANING, [1 if value else 0], **kwargs)


def frame_set_rgbw(
    red: int,
    green: int,
    blue: int,
    *,
    rgb_on: bool = True,
    model: str | None = None,
    **kwargs: str,
) -> str:
    """RGB colour (set_Rgbw).

    M002 and most variants expect ``[RGB_Sw, R, G, B]``. Models listed in
    ``RGB_MODELS_WITHOUT_SWITCH`` (e.g. M001) take only ``[R, G, B]``.
    """
    for value in (red, green, blue):
        if not 0 <= value <= 255:
            raise ValueError(f"colour component out of range (0-255): {value}")
    if model in RGB_MODELS_WITHOUT_SWITCH:
        payload = [red, green, blue]
    else:
        payload = [1 if rgb_on else 0, red, green, blue]
    return build_frame(CMD_SET_RGBW, payload, **kwargs)


def frame_timing(hour: int, minute: int, second: int, **kwargs: str) -> str:
    """Set the device clock (timing_Set)."""
    if not (0 <= hour <= 23 and 0 <= minute <= 59 and 0 <= second <= 59):
        raise ValueError("time component out of range")
    return build_frame(CMD_TIMING, [hour, minute, second], **kwargs)
