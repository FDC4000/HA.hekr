from __future__ import annotations

from typing import Any

from homeassistant.components.diagnostics import async_redact_data
from homeassistant.const import CONF_PASSWORD, CONF_USERNAME
from homeassistant.core import HomeAssistant

from .coordinator import HekrConfigEntry

TO_REDACT = {
    CONF_PASSWORD,
    CONF_USERNAME,
    "access_token",
    "refresh_token",
    "token",
    "ctrlKey",
    "productPublicKey",
    "bindKey",
    "mac",
    "lanIp",
    "mid",
    "user",
}


async def async_get_config_entry_diagnostics(
    hass: HomeAssistant, entry: HekrConfigEntry
) -> dict[str, Any]:
    """Return redacted diagnostics for a config entry."""
    coordinator = entry.runtime_data
    return {
        "entry_data": async_redact_data(dict(entry.data), TO_REDACT),
        "options": dict(entry.options),
        "websocket_connected": coordinator.available,
        "checksum_mode": coordinator.checksum_mode,
        "devices": async_redact_data(coordinator.devices, TO_REDACT),
        "status": async_redact_data(coordinator.data or {}, TO_REDACT),
    }
