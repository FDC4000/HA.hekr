from __future__ import annotations

import math
from typing import Any

from homeassistant.components.fan import FanEntity, FanEntityFeature
from homeassistant.core import HomeAssistant
from homeassistant.helpers.entity_platform import AddConfigEntryEntitiesCallback
from homeassistant.util.percentage import (
    percentage_to_ranged_value,
    ranged_value_to_percentage,
)

from . import protocol
from .const import FIELD_SPEED, SPEED_MAX, SPEED_MIN
from .coordinator import HekrConfigEntry
from .entity import HekrEntity

_SPEED_RANGE = (SPEED_MIN, SPEED_MAX)  # (1, 4)


async def async_setup_entry(
    hass: HomeAssistant,
    entry: HekrConfigEntry,
    async_add_entities: AddConfigEntryEntitiesCallback,
) -> None:
    """Set up the fan entities."""
    coordinator = entry.runtime_data
    async_add_entities(HekrFan(coordinator, tid) for tid in coordinator.devices)


class HekrFan(HekrEntity, FanEntity):
    """The extractor fan, mapped to the device 'speed' field (0=off, 1-4)."""

    _attr_name = None  # the device itself represents the fan
    _attr_supported_features = (
        FanEntityFeature.SET_SPEED
        | FanEntityFeature.TURN_ON
        | FanEntityFeature.TURN_OFF
    )
    _attr_speed_count = SPEED_MAX

    def __init__(self, coordinator, dev_tid: str) -> None:
        super().__init__(coordinator, dev_tid)
        self._attr_unique_id = f"{dev_tid}_fan"

    @property
    def _speed(self) -> int:
        return int(self._status.get(FIELD_SPEED, 0) or 0)

    @property
    def is_on(self) -> bool:
        return self._speed > 0

    @property
    def percentage(self) -> int:
        if self._speed <= 0:
            return 0
        return ranged_value_to_percentage(_SPEED_RANGE, self._speed)

    async def async_set_percentage(self, percentage: int) -> None:
        if percentage == 0:
            await self._async_set_speed(0)
            return
        speed = math.ceil(percentage_to_ranged_value(_SPEED_RANGE, percentage))
        await self._async_set_speed(max(SPEED_MIN, min(SPEED_MAX, speed)))

    async def async_turn_on(
        self,
        percentage: int | None = None,
        preset_mode: str | None = None,
        **kwargs: Any,
    ) -> None:
        if percentage is not None:
            await self.async_set_percentage(percentage)
        else:
            await self._async_set_speed(SPEED_MIN)

    async def async_turn_off(self, **kwargs: Any) -> None:
        await self._async_set_speed(0)

    async def _async_set_speed(self, speed: int) -> None:
        raw = protocol.frame_set_speed(
            speed, checksum_mode=self.coordinator.checksum_mode
        )
        await self._async_send(raw)
