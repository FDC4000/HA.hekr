from __future__ import annotations

import logging
from typing import Any

import aiohttp

from .const import (
    APP_LOGIN_INFO,
    DEVICE_URL,
    LOGIN_URL,
    TEMPLATE_URL,
    USER_AGENT,
)

_LOGGER = logging.getLogger(__name__)

_TIMEOUT = aiohttp.ClientTimeout(total=30)


class HekrError(Exception):
    """Base error for the Hekr cloud client."""


class HekrAuthError(HekrError):
    """Raised when authentication fails (bad credentials / expired token)."""


class HekrConnectionError(HekrError):
    """Raised when the cloud cannot be reached."""


class HekrCloudApi:
    """Thin async wrapper around the three Hekr cloud REST endpoints."""

    def __init__(self, session: aiohttp.ClientSession) -> None:
        self._session = session

    async def async_login(self, username: str, password: str) -> dict[str, Any]:
        """Log in and return the session dict (access_token, expires_in, ...).

        Raises :class:`HekrAuthError` on HTTP 401 and
        :class:`HekrConnectionError` on transport failures.
        """
        payload = {
            "username": username,
            "password": password,
            "clientType": "IOS",
            "appLoginInfo": APP_LOGIN_INFO,
            "pid": "00000000000",
        }
        headers = {
            "Content-Type": "application/json",
            "Accept": "*/*",
            "Accept-Language": "de",
        }
        try:
            async with self._session.post(
                LOGIN_URL, json=payload, headers=headers, timeout=_TIMEOUT
            ) as resp:
                if resp.status in (400, 401, 403):
                    raise HekrAuthError(f"login rejected (HTTP {resp.status})")
                resp.raise_for_status()
                data = await resp.json()
        except aiohttp.ClientError as err:
            raise HekrConnectionError(str(err)) from err

        if not data.get("access_token"):
            raise HekrAuthError("login response contained no access_token")
        _LOGGER.debug("Login successful (token expires in %ss)", data.get("expires_in"))
        return data

    async def async_get_devices(self, token: str) -> list[dict[str, Any]]:
        """Return the account's device list."""
        data = await self._get(DEVICE_URL, token)
        if not isinstance(data, list):
            raise HekrError(f"unexpected device list payload: {type(data)}")
        _LOGGER.debug("Fetched %d device(s)", len(data))
        return data

    async def async_get_template(
        self, token: str, product_public_key: str
    ) -> dict[str, Any]:
        """Return the protocol template for a product public key."""
        return await self._get(
            TEMPLATE_URL, token, extra_headers={"X-Hekr-ProdPubKey": product_public_key}
        )

    async def _get(
        self,
        url: str,
        token: str,
        extra_headers: dict[str, str] | None = None,
    ) -> Any:
        headers = {
            "Accept": "*/*",
            "User-Agent": USER_AGENT,
            "Accept-Language": "de",
            "Authorization": f"Bearer {token}",
        }
        if extra_headers:
            headers.update(extra_headers)
        try:
            async with self._session.get(
                url, headers=headers, timeout=_TIMEOUT
            ) as resp:
                if resp.status in (401, 403):
                    raise HekrAuthError(f"request unauthorized (HTTP {resp.status})")
                resp.raise_for_status()
                return await resp.json()
        except aiohttp.ClientError as err:
            raise HekrConnectionError(str(err)) from err
