from __future__ import annotations

import logging
from collections.abc import Mapping
from typing import Any

import voluptuous as vol
from homeassistant.config_entries import (
    ConfigEntry,
    ConfigFlow,
    ConfigFlowResult,
    OptionsFlow,
)
from homeassistant.const import CONF_PASSWORD, CONF_USERNAME
from homeassistant.core import callback
from homeassistant.helpers.aiohttp_client import async_get_clientsession
from homeassistant.helpers.selector import (
    BooleanSelector,
    SelectSelector,
    SelectSelectorConfig,
    SelectSelectorMode,
)

from .api import HekrAuthError, HekrCloudApi, HekrConnectionError
from .const import (
    CHECKSUM_CALC,
    CHECKSUM_ZERO,
    CONF_CHECKSUM_MODE,
    CONF_USE_UDP,
    DATA_DEVICES,
    DOMAIN,
)

_LOGGER = logging.getLogger(__name__)

STEP_USER_SCHEMA = vol.Schema(
    {
        vol.Required(CONF_USERNAME): str,
        vol.Required(CONF_PASSWORD): str,
    }
)


class HekrConfigFlow(ConfigFlow, domain=DOMAIN):
    """Handle the config flow."""

    VERSION = 1

    reauth_entry: ConfigEntry | None = None

    async def async_step_user(
        self, user_input: dict[str, Any] | None = None
    ) -> ConfigFlowResult:
        """Handle the initial login step."""
        errors: dict[str, str] = {}
        if user_input is not None:
            username = user_input[CONF_USERNAME]
            api = HekrCloudApi(async_get_clientsession(self.hass))
            try:
                session = await api.async_login(username, user_input[CONF_PASSWORD])
                devices = await api.async_get_devices(session["access_token"])
            except HekrAuthError:
                errors["base"] = "invalid_auth"
            except HekrConnectionError:
                errors["base"] = "cannot_connect"
            except Exception:  # noqa: BLE001
                _LOGGER.exception("Unexpected error during setup")
                errors["base"] = "unknown"
            else:
                await self.async_set_unique_id(username.lower())
                self._abort_if_unique_id_configured()
                return self.async_create_entry(
                    title=username,
                    data={
                        CONF_USERNAME: username,
                        CONF_PASSWORD: user_input[CONF_PASSWORD],
                        DATA_DEVICES: devices,
                    },
                )

        return self.async_show_form(
            step_id="user", data_schema=STEP_USER_SCHEMA, errors=errors
        )

    async def async_step_reauth(
        self, entry_data: Mapping[str, Any]
    ) -> ConfigFlowResult:
        """Handle re-authentication when the token/credentials are rejected."""
        self.reauth_entry = self.hass.config_entries.async_get_entry(
            self.context["entry_id"]
        )
        return await self.async_step_reauth_confirm()

    async def async_step_reauth_confirm(
        self, user_input: dict[str, Any] | None = None
    ) -> ConfigFlowResult:
        """Confirm re-authentication with a new password."""
        errors: dict[str, str] = {}
        assert self.reauth_entry is not None
        username = self.reauth_entry.data[CONF_USERNAME]
        if user_input is not None:
            api = HekrCloudApi(async_get_clientsession(self.hass))
            try:
                await api.async_login(username, user_input[CONF_PASSWORD])
            except HekrAuthError:
                errors["base"] = "invalid_auth"
            except HekrConnectionError:
                errors["base"] = "cannot_connect"
            else:
                return self.async_update_reload_and_abort(
                    self.reauth_entry,
                    data={
                        **self.reauth_entry.data,
                        CONF_PASSWORD: user_input[CONF_PASSWORD],
                    },
                )

        return self.async_show_form(
            step_id="reauth_confirm",
            data_schema=vol.Schema({vol.Required(CONF_PASSWORD): str}),
            description_placeholders={"username": username},
            errors=errors,
        )

    @staticmethod
    @callback
    def async_get_options_flow(config_entry: ConfigEntry) -> HekrOptionsFlow:
        """Return the options flow."""
        return HekrOptionsFlow()


class HekrOptionsFlow(OptionsFlow):
    """Handle UDP / checksum options."""

    async def async_step_init(
        self, user_input: dict[str, Any] | None = None
    ) -> ConfigFlowResult:
        """Manage the options."""
        if user_input is not None:
            return self.async_create_entry(data=user_input)

        options = self.config_entry.options
        schema = vol.Schema(
            {
                vol.Optional(
                    CONF_USE_UDP,
                    default=options.get(CONF_USE_UDP, False),
                ): BooleanSelector(),
                vol.Optional(
                    CONF_CHECKSUM_MODE,
                    default=options.get(CONF_CHECKSUM_MODE, CHECKSUM_CALC),
                ): SelectSelector(
                    SelectSelectorConfig(
                        options=[CHECKSUM_CALC, CHECKSUM_ZERO],
                        translation_key=CONF_CHECKSUM_MODE,
                        mode=SelectSelectorMode.DROPDOWN,
                    )
                ),
            }
        )
        return self.async_show_form(step_id="init", data_schema=schema)
