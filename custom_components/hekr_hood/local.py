"""Local LAN (UDP) command transport for Hekr devices.

Generated by aurora@aurora-smart-home (ha-integration-dev skill)
https://github.com/tonylofgren/aurora-smart-home

Ported from the ioBroker.hekr adapter by TA2k
(https://github.com/TA2k/ioBroker.hekr), MIT License, Copyright (c) 2021 TA2k.

The original adapter sends commands to the device's LAN IP on UDP port 10000 as
a fire-and-forget datagram (it never reads a reply). We mirror that: the local
path carries *commands* only; status still arrives via the cloud WebSocket.
"""

from __future__ import annotations

import asyncio
import json
import logging

from .const import APP_TID, LOCAL_UDP_PORT, UDP_MSG_APP_SEND

_LOGGER = logging.getLogger(__name__)


def build_app_send_payload(dev_tid: str, ctrl_key: str, raw: str) -> bytes:
    """Build the JSON datagram used for both the UDP and WebSocket appSend."""
    return json.dumps(
        {
            "action": "appSend",
            "msgId": UDP_MSG_APP_SEND,
            "params": {
                "appTid": APP_TID,
                "devTid": dev_tid,
                "ctrlKey": ctrl_key,
                "data": {"raw": raw},
            },
        }
    ).encode()


async def async_send_local(
    lan_ip: str, dev_tid: str, ctrl_key: str, raw: str
) -> None:
    """Send a single raw command to the device over UDP (fire-and-forget)."""
    loop = asyncio.get_running_loop()
    message = build_app_send_payload(dev_tid, ctrl_key, raw)
    transport, _ = await loop.create_datagram_endpoint(
        asyncio.DatagramProtocol, remote_addr=(lan_ip, LOCAL_UDP_PORT)
    )
    try:
        transport.sendto(message)
        _LOGGER.debug("Sent local UDP command to %s:%s", lan_ip, LOCAL_UDP_PORT)
    finally:
        transport.close()
