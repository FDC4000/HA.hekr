# The author's README states that writing the 'cleaning' field to 0 clears the
# filter-change reminder (command cmdId 6, rest_Cleaning). The enumeration also
# allows 1; this value could not be verified against the physical hood (offline
# during development). Change here if 0 proves ineffective on your unit.
_RESET_VALUE = 0


async def async_setup_entry(
    hass: HomeAssistant,
    entry: HekrConfigEntry,
    async_add_entities: AddConfigEntryEntitiesCallback,
) -> None:
    """Set up the filter-reset button."""
    coordinator = entry.runtime_data
    async_add_entities(HekrFilterResetButton(coordinator, tid) for tid in coordinator.devices)


class HekrFilterResetButton(HekrEntity, ButtonEntity):
    """Reset the filter-change reminder (rest_Cleaning)."""

    _attr_translation_key = "reset_filter"

    def __init__(self, coordinator, dev_tid: str) -> None:
        super().__init__(coordinator, dev_tid)
        self._attr_unique_id = f"{dev_tid}_reset_filter"

    async def async_press(self) -> None:
        raw = protocol.frame_reset_cleaning(
            _RESET_VALUE, checksum_mode=self.coordinator.checksum_mode
        )
        await self._async_send(raw)
