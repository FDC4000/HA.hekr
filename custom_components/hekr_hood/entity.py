"""Base entity for the Hekr Hood integration.

Generated by aurora@aurora-smart-home (ha-integration-dev skill)
https://github.com/tonylofgren/aurora-smart-home
"""

from __future__ import annotations

from typing import Any

from homeassistant.helpers.device_info import DeviceInfo
from homeassistant.helpers.update_coordinator import CoordinatorEntity

from .const import DOMAIN, MANUFACTURER
from .coordinator import HekrCoordinator


class HekrEntity(CoordinatorEntity[HekrCoordinator]):
    """Common base: device_info, availability and status access."""

    _attr_has_entity_name = True

    def __init__(self, coordinator: HekrCoordinator, dev_tid: str) -> None:
        super().__init__(coordinator)
        self._dev_tid = dev_tid
        device = coordinator.devices.get(dev_tid, {})
        self._attr_device_info = DeviceInfo(
            identifiers={(DOMAIN, dev_tid)},
            name=coordinator.device_name(dev_tid),
            manufacturer=MANUFACTURER,
            model=device.get("model"),
            sw_version=device.get("binVersion"),
        )

    @property
    def _status(self) -> dict[str, Any]:
        """Return the latest status dict for this device."""
        return (self.coordinator.data or {}).get(self._dev_tid, {})

    @property
    def available(self) -> bool:
        """Available only while the cloud WebSocket is connected."""
        return self.coordinator.available and super().available

    async def _async_send(self, raw: str) -> None:
        """Send a raw frame; the device reports the new state back via push."""
        await self.coordinator.async_send_raw(self._dev_tid, raw)
